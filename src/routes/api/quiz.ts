import { createFileRoute } from "@tanstack/react-router";
import { generateText } from "ai";
import { getShivaProviders } from "@/lib/ai-providers.server";

type QuizQuestion = { question: string; options: string[]; answerIndex: number; explanation: string };

function parseQuiz(raw: string, count: number) {
  const cleaned = raw.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "").trim();
  const start = cleaned.indexOf("{");
  const end = cleaned.lastIndexOf("}");
  if (start < 0 || end <= start) throw new Error("The AI returned an invalid quiz format.");
  const parsed = JSON.parse(cleaned.slice(start, end + 1)) as { title?: string; questions?: QuizQuestion[] };
  if (!Array.isArray(parsed.questions) || parsed.questions.length !== count) throw new Error("The generated quiz did not contain the requested number of questions.");
  for (const [index, q] of parsed.questions.entries()) {
    if (typeof q.question !== "string" || !Array.isArray(q.options) || q.options.length !== 4 ||
        !q.options.every((option) => typeof option === "string") ||
        !Number.isInteger(q.answerIndex) || q.answerIndex < 0 || q.answerIndex > 3 ||
        typeof q.explanation !== "string") {
      throw new Error(`Question ${index + 1} was incomplete. Please generate the quiz again.`);
    }
  }
  return { title: (parsed.title || "Practice Quiz").slice(0, 100), questions: parsed.questions };
}

export const Route = createFileRoute("/api/quiz")({
  server: {
    handlers: {
      POST: async ({ request }) => {
        try {
          const body = await request.json() as { topic?: string; count?: number; difficulty?: string };
          const topic = typeof body.topic === "string" ? body.topic.trim().slice(0, 240) : "";
          const count = [5, 10, 15].includes(Number(body.count)) ? Number(body.count) : 5;
          const difficulty = ["Easy", "Medium", "Hard", "Mixed"].includes(String(body.difficulty)) ? String(body.difficulty) : "Mixed";
          if (!topic) return Response.json({ error: "A quiz topic is required." }, { status: 400 });

          const providers = getShivaProviders();
          if (!providers.length) return Response.json({ error: "No AI provider is configured." }, { status: 503 });
          const failures: string[] = [];
          for (const provider of providers) {
            try {
              const result = await generateText({
                model: provider.model,
                maxRetries: 0,
                system: "You are Shiva AI's quiz author. Create accurate educational multiple-choice quizzes. Return ONLY valid JSON, with no markdown fences, in this exact shape: { title: string, questions: [{ question: string, options: [string,string,string,string], answerIndex: number, explanation: string }] }. answerIndex is zero-based. Exactly one option must be correct. Explanations should briefly teach why the answer is correct. Avoid ambiguous questions.",
                prompt: `Create exactly ${count} multiple-choice questions about: ${topic}. Difficulty: ${difficulty}. Use clear student-friendly wording and four plausible options per question. If the topic is a school subject, match the requested difficulty and do not invent facts. Return JSON only.`,
              });
              const quiz = parseQuiz(result.text, count);
              console.info(`Shiva AI quiz generated by ${provider.name}`);
              return Response.json({ quiz, provider: provider.name });
            } catch (error) {
              const detail = error instanceof Error ? error.message : "Unknown provider error";
              console.error(`Shiva AI quiz ${provider.name} failed:`, detail);
              failures.push(`${provider.name}: ${detail.slice(0, 180)}`);
            }
          }
          return Response.json({ error: "All configured AI providers failed to create the quiz.", detail: failures.join(" | ").slice(0, 800) }, { status: 502 });
        } catch (error) {
          console.error("Shiva AI /api/quiz error:", error);
          return Response.json({ error: "Quiz generation failed.", detail: error instanceof Error ? error.message.slice(0, 400) : "Unknown error" }, { status: 500 });
        }
      },
    },
  },
});
